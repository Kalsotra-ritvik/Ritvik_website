/**
 * Media storage abstraction.
 *
 *  - local: files under LOCAL_UPLOAD_DIR (default .data/uploads), served by
 *    app/media/[...key]/route.ts. For development and self-hosted servers with
 *    a persistent disk. Disabled on Vercel, whose filesystem is not persistent.
 *  - r2:    Cloudflare R2 through its S3-compatible API (signed with aws4fetch).
 *    Large files upload directly from the browser with presigned URLs.
 *
 * Configuration is read from server-side environment variables only.
 */
import "server-only";
import { promises as fs } from "node:fs";
import path from "node:path";
import { AwsClient } from "aws4fetch";

export type StorageDriver = "local" | "r2";

export interface StorageAdapter {
  driver: StorageDriver;
  /** Largest body the server itself will accept for an upload. */
  maxServerUpload: number;
  supportsDirectUpload: boolean;
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
  remove(key: string): Promise<void>;
  publicUrl(key: string): string;
  readStart(key: string, bytes: number): Promise<Uint8Array>;
  presignPut?(key: string, contentType: string): Promise<{ url: string; headers: Record<string, string> }>;
}

export interface StorageStatus {
  driver: StorageDriver | "none";
  ready: boolean;
  message: string;
  missing: string[];
}

const onVercel = () => Boolean(process.env.VERCEL);
// Vercel functions accept request bodies up to 4.5 MB; stay safely below it.
const VERCEL_BODY_LIMIT = 4 * 1024 * 1024;

function requestedDriver(): StorageDriver | null {
  const v = process.env.STORAGE_DRIVER?.trim().toLowerCase();
  if (v === "local" || v === "r2") return v;
  return null;
}

const R2_VARS = ["R2_ACCOUNT_ID", "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "R2_BUCKET", "R2_PUBLIC_BASE_URL"] as const;

export function storageStatus(): StorageStatus {
  const driver = requestedDriver() ?? (onVercel() ? "r2" : process.env.NODE_ENV === "production" ? null : "local");
  if (driver === "r2") {
    const missing = R2_VARS.filter((v) => !process.env[v]?.trim());
    return missing.length
      ? {
          driver: "r2",
          ready: false,
          missing,
          message: `Uploads need Cloudflare R2. Set ${missing.join(", ")}. Text editing and publishing work without it.`,
        }
      : { driver: "r2", ready: true, missing: [], message: "Uploads go to Cloudflare R2." };
  }
  if (driver === "local") {
    if (onVercel())
      return {
        driver: "local",
        ready: false,
        missing: [],
        message: "Local file storage is not persistent on Vercel. Set STORAGE_DRIVER=r2 and the R2 variables to enable uploads.",
      };
    return { driver: "local", ready: true, missing: [], message: `Uploads are stored on this server's disk (${localDir()}).` };
  }
  return {
    driver: "none",
    ready: false,
    missing: ["STORAGE_DRIVER"],
    message: "No media storage is configured. Set STORAGE_DRIVER=r2 (or local on a server with a persistent disk).",
  };
}

function localDir() {
  // Runtime-configured directory outside the build output; not traced by the bundler.
  return path.resolve(/* turbopackIgnore: true */ process.env.LOCAL_UPLOAD_DIR?.trim() || ".data/uploads");
}

/** Keys are generated by the server ("yyyy/mm/uuid-name.ext"); reject anything else. */
export function assertSafeKey(key: string) {
  if (!/^[0-9]{4}\/[0-9]{2}\/[a-f0-9-]{36}-[a-z0-9._-]{1,80}$/.test(key)) throw new Error("Invalid storage key");
}

function localAdapter(): StorageAdapter {
  const root = localDir();
  const file = (key: string) => {
    assertSafeKey(key);
    const p = path.resolve(root, key);
    if (!p.startsWith(root + path.sep)) throw new Error("Invalid storage key");
    return p;
  };
  return {
    driver: "local",
    maxServerUpload: 100 * 1024 * 1024,
    supportsDirectUpload: false,
    async put(key, body) {
      const p = file(key);
      await fs.mkdir(path.dirname(p), { recursive: true });
      await fs.writeFile(p, body, { flag: "wx" });
    },
    async remove(key) {
      await fs.rm(file(key), { force: true });
    },
    publicUrl(key) {
      return `/media/${key}`;
    },
    async readStart(key, bytes) {
      const handle = await fs.open(file(key), "r");
      try {
        const buf = Buffer.alloc(bytes);
        const { bytesRead } = await handle.read(buf, 0, bytes, 0);
        return new Uint8Array(buf.subarray(0, bytesRead));
      } finally {
        await handle.close();
      }
    },
  };
}

export async function readLocalFile(key: string): Promise<Buffer | null> {
  const root = localDir();
  try {
    assertSafeKey(key);
  } catch {
    return null;
  }
  const p = path.resolve(root, key);
  if (!p.startsWith(root + path.sep)) return null;
  try {
    return await fs.readFile(p);
  } catch {
    return null;
  }
}

function r2Adapter(): StorageAdapter {
  const account = process.env.R2_ACCOUNT_ID!.trim();
  const bucket = process.env.R2_BUCKET!.trim();
  const publicBase = process.env.R2_PUBLIC_BASE_URL!.trim().replace(/\/+$/, "");
  const client = new AwsClient({
    accessKeyId: process.env.R2_ACCESS_KEY_ID!.trim(),
    secretAccessKey: process.env.R2_SECRET_ACCESS_KEY!.trim(),
    service: "s3",
    region: "auto",
  });
  const objectUrl = (key: string) => {
    assertSafeKey(key);
    return `https://${account}.r2.cloudflarestorage.com/${encodeURIComponent(bucket)}/${key}`;
  };
  const check = async (res: Response, action: string) => {
    if (!res.ok) throw new Error(`R2 ${action} failed (${res.status}): ${(await res.text()).slice(0, 200)}`);
  };
  return {
    driver: "r2",
    maxServerUpload: onVercel() ? VERCEL_BODY_LIMIT : 50 * 1024 * 1024,
    supportsDirectUpload: true,
    async put(key, body, contentType) {
      const res = await client.fetch(objectUrl(key), {
        method: "PUT",
        body: body as unknown as BodyInit,
        headers: { "content-type": contentType },
      });
      await check(res, "upload");
    },
    async remove(key) {
      const res = await client.fetch(objectUrl(key), { method: "DELETE" });
      if (res.status !== 404) await check(res, "delete");
    },
    publicUrl(key) {
      return `${publicBase}/${key}`;
    },
    async readStart(key, bytes) {
      const res = await client.fetch(objectUrl(key), { headers: { range: `bytes=0-${bytes - 1}` } });
      await check(res, "read");
      return new Uint8Array(await res.arrayBuffer());
    },
    async presignPut(key, contentType) {
      const url = new URL(objectUrl(key));
      url.searchParams.set("X-Amz-Expires", "600");
      const signed = await client.sign(url.toString(), {
        method: "PUT",
        headers: { "content-type": contentType },
        aws: { signQuery: true },
      });
      return { url: signed.url, headers: { "content-type": contentType } };
    },
  };
}

export class StorageNotConfiguredError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "StorageNotConfiguredError";
  }
}

export function getStorage(): StorageAdapter {
  const status = storageStatus();
  if (!status.ready) throw new StorageNotConfiguredError(status.message);
  return status.driver === "r2" ? r2Adapter() : localAdapter();
}

